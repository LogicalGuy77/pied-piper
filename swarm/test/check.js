// Step 3 checks: does the swarm give the same answer as one model?
//
// Starts the real tracker, then runs six phones as Peer objects in this
// process. They fetch their weights over HTTP and talk only through the
// tracker's WebSocket, the same path a browser tab uses.
//
//  1. The tokenizer gives Hugging Face's ids, and decodes them back.
//  2. Frames survive encode/decode bit for bit.
//  3. Asking before every block has a holder fails clearly.
//  4. Six phones end up two per block.
//  5. The greedy answer through the swarm equals the Python reference's
//     (Hugging Face's, for float32).
//  6. The h sent between phones is bit-identical to step 2's in-process run.
//  7. Two askers at once get different routes and their solo answers.
//  8. A phone leaving mid-answer: the answer is rerouted and is still exactly
//     right; with no other holder of its block, the asker gets a clear error.
//  9. When sessions end, every phone frees their KV caches.
// 10. A phone silent while it computes is kept; silent while idle, dropped.
// 11. Phones get a small summary; the dashboard gets everything, and a QR code.
//
//   cd swarm && npm run check           # int8, what the tracker serves by default
//   cd swarm && npm run check:float32   # float32 against Hugging Face's answer

import { spawn } from "node:child_process";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { WebSocket as RawSocket } from "ws";

import { openWeights } from "../../engine/src/node-files.js";
import { argmax, generate, Pipeline } from "../../engine/src/pipeline.js";
import { Stage } from "../../engine/src/stage.js";
import { Peer } from "../src/peer.js";
import { decodeFrame, encodeFrame, KIND, readHeader } from "../src/protocol.js";
import { Tokenizer } from "../src/tokenizer.js";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const WEIGHTS = process.argv[2] ?? join(ROOT, "weights", "smollm2-135m-instruct-int8");
const VECTORS = process.argv[3] ?? join(ROOT, "testvectors-int8");
const BOUNDARIES = [0, 8, 22, 30];
const SHORT = 8; // tokens generated by the runs in checks 7 and 8

const results = [];
function check(name, ok, detail = "") {
  results.push(ok);
  console.log(`  ${ok ? "PASS" : "FAIL"}  ${name}${detail ? `  (${detail})` : ""}`);
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const bytesOf = (a) => new Uint8Array(a.buffer, a.byteOffset, a.byteLength);
function sameBytes(a, b) {
  const x = bytesOf(a), y = bytesOf(b);
  return x.length === y.length && x.every((v, i) => v === y[i]);
}
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
async function until(cond, ms = 3000) {
  for (const end = Date.now() + ms; Date.now() < end; await wait(20)) if (cond()) return true;
  return cond();
}

async function collect(stream, onStep = () => {}) {
  const steps = [];
  for await (const step of stream) {
    steps.push(step);
    onStep(step, steps.length);
  }
  return steps;
}

const t0 = performance.now();
const index = JSON.parse(await readFile(join(VECTORS, "index.json"), "utf8"));
// The tokenizer vectors don't depend on the weights' dtype, so the int8 run reuses testvectors/.
const tokVectors = JSON.parse(await readFile(join(VECTORS, "tokenizer.json"), "utf8")
  .catch(() => readFile(join(ROOT, "testvectors", "tokenizer.json"), "utf8")));
const tok = new Tokenizer(JSON.parse(await readFile(join(WEIGHTS, "tokenizer", "tokenizer.json"), "utf8")));
const EOS = tok.eosId;
const REFERENCE = JSON.parse(await readFile(join(WEIGHTS, "manifest.json"), "utf8")).dtype === "int8"
  ? "the int8 reference's" : "Hugging Face's";

console.log("1. Tokenizer vs Hugging Face");
{
  const strings = tokVectors.strings;
  const badEncode = strings.filter((s) => !same(tok.encode(s.text), s.ids));
  check(`encode gives the same ids on ${strings.length} strings`, badEncode.length === 0,
    badEncode.map((s) => JSON.stringify(s.text.slice(0, 30))).join(", "));
  const badDecode = strings.filter((s) => tok.decode(s.ids) !== s.decoded);
  check("decode gives the same text", badDecode.length === 0, badDecode.map((s) => JSON.stringify(s.text.slice(0, 30))).join(", "));
  const badChat = tokVectors.chats.filter((c) => tok.chatText(c.messages) !== c.text || !same(tok.chat(c.messages), c.ids));
  check(`chat template gives the same ids on ${tokVectors.chats.length} chats`, badChat.length === 0);
  const prompt = tok.chat([{ role: "user", content: index.prompt }]);
  check("the step 1 prompt tokenizes to the step 1 prompt ids", same(prompt, index.prompt_ids));
  const d = tok.streamDecoder();
  const streamed = strings.at(17).ids.map((id) => d.push(id)).join("") + d.flush();
  check("decoding one token at a time holds back split characters", streamed === strings.at(17).decoded,
    `${JSON.stringify(streamed)}`);
}

console.log("2. Frames");
{
  const h = new Float32Array(3 * 576).map(() => Math.random() * 2 - 1);
  h[0] = -0; h[1] = NaN; h[2] = 1e-40;
  const header = { kind: KIND.HIDDEN, hop: 2, attempt: 3, session: 4000000000, pos: 70000, n: 3 };
  const f = decodeFrame(encodeFrame(header, h));
  const headerOk = f.kind === header.kind && f.hop === 2 && f.attempt === 3 && f.session === header.session && f.pos === 70000 && f.n === 3;
  const t = decodeFrame(encodeFrame({ kind: KIND.TOKENS, hop: 0, session: 1, pos: 0, n: 3 }, Int32Array.of(1, 49151, 2)));
  // The tracker reads headers from Node Buffers, which can start at any offset.
  const unaligned = Buffer.concat([Buffer.alloc(3), Buffer.from(encodeFrame(header, h))]).subarray(3);
  check("h, -0, NaN and subnormals survive bit for bit; token ids too", headerOk && sameBytes(f.payload, h) && same([...t.payload], [1, 49151, 2]),
    `${encodeFrame(header, h.subarray(0, 576)).byteLength} bytes for one token`);
  check("the tracker reads the header from an unaligned Buffer", same(readHeader(unaligned), header));
}

// --- Local references, computed before any phone runs ---
// The test phones share this process, so a long computation here would stop
// them answering the tracker's heartbeat. Everything slow happens first.

const prompt = index.prompt_ids;
const greedy = index.greedy_tokens;
const otherPrompt = tok.chat([{ role: "user", content: "What is the capital of France?" }]);
const reference = { h1: [], h2: [], otherTokens: null };
const local = []; // the three blocks in this process; check 10's phone serves one of them
{
  const weights = await openWeights(WEIGHTS);
  for (let i = 0; i < 3; i++) local.push(await Stage.load({ ...weights, start: BOUNDARIES[i], end: BOUNDARIES[i + 1] }));
  let ids = Int32Array.from(prompt), pos = 0;
  for (let i = 0; i < greedy.length; i++) {
    reference.h1.push(local[0].forward("local", ids, pos));
    reference.h2.push(local[1].forward("local", reference.h1[i], pos));
    local[2].forward("local", reference.h2[i], pos, { lastOnly: true });
    pos += ids.length;
    ids = Int32Array.of(greedy[i]);
  }
  reference.otherTokens = generate(new Pipeline(local), "solo", otherPrompt, SHORT, new Set([EOS])).tokens;
}

// --- Start the tracker and the phones ---

// The heartbeat timeout is longer than the 5 s default: these phones answer
// pings from JS, and the reference work in this process can hold it for a
// few seconds. (A browser answers pings outside the page's JS.)
const HEARTBEAT_MS = 8000;
const tracker = spawn(process.execPath, [join(ROOT, "swarm", "tracker.js"), "--port", "0", "--host", "127.0.0.1", "--weights", WEIGHTS,
  "--heartbeat-timeout", String(HEARTBEAT_MS)], { stdio: ["ignore", "pipe", "inherit"] });
const trackerLog = [];
const server = await new Promise((resolve, reject) => {
  tracker.on("exit", (code) => reject(new Error(`tracker exited with ${code}`)));
  tracker.stdout.on("data", (chunk) => {
    trackerLog.push(...chunk.toString().trim().split("\n"));
    const m = chunk.toString().match(/listening on (https?:\S+)/);
    if (m) resolve(m[1]);
  });
});

// Every phone fetches over HTTP; the first fetch of each file is shared, so
// six phones in one process don't hold six copies of the weights.
const fetched = new Map();
const sharedRead = (name) => {
  if (!fetched.has(name)) {
    fetched.set(name, fetch(`${server}/weights/${name}`).then((r) => {
      if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
      return r.arrayBuffer();
    }));
  }
  return fetched.get(name);
};

// The dashboard's view: the tracker's full state.
const watch = { state: null, messages: 0 };
{
  const ws = new RawSocket(server.replace(/^http/, "ws") + "/ws");
  ws.on("open", () => ws.send(JSON.stringify({ type: "watch" })));
  ws.on("message", (data) => {
    watch.state = JSON.parse(data.toString());
    watch.messages++;
  });
  await until(() => watch.state);
}
const listed = (id) => watch.state.peers.some((p) => p.id === id);

const sent = []; // every binary frame any phone sends: { from, frame }
const swarmState = new Map(); // phone id -> latest swarm summary it received
async function startPeer() {
  const peer = new Peer({ server, readFile: sharedRead });
  peer.tap = (buf) => sent.push({ from: peer.id, frame: decodeFrame(buf.slice(0)) });
  peer.onEvent = (e) => e.type === "swarm" && swarmState.set(peer.id, e);
  await peer.connect();
  await peer.load();
  return peer;
}
console.log("3. Asking with blocks missing");
const phones = [await startPeer()];
{
  let error = null;
  try {
    await collect(phones[0].ask(prompt, { maxNew: 1 }));
  } catch (err) {
    error = err.message;
  }
  check("asking with only block 1 in the swarm fails clearly", /waiting for block 2/.test(error ?? ""), error ?? "no error");
}

console.log("4. Joining");
for (let i = 1; i < 6; i++) phones.push(await startPeer());
{
  const perBlock = [0, 1, 2].map((b) => phones.filter((p) => p.block.index === b).map((p) => p.id));
  check("six phones get two per block", perBlock.every((ids) => ids.length === 2), perBlock.map((ids, b) => `block ${b + 1}: ${ids.join(",")}`).join("  "));
  const describe = phones.slice(0, 3).map((p) => p.stage.describe());
  check("each phone loads only its block", same(describe, ["embedding + layers 0–7", "layers 8–21", "layers 22–29 + output"]), describe.join(" | "));
}

console.log("5. One answer through the swarm");
const asker = phones[0];
let mainSession = null;
{
  const steps = await collect(asker.ask(prompt, { maxNew: greedy.length, stopIds: [EOS] }));
  mainSession = steps[0].session;
  const tokens = steps.map((x) => x.token);
  const matched = tokens.filter((t, i) => t === greedy[i]).length;
  const perToken = steps.slice(1).reduce((sum, x) => sum + x.ms, 0) / (steps.length - 1);
  check(`greedy tokens equal ${REFERENCE}`, same(tokens, greedy),
    `${matched} of ${greedy.length}, route ${steps[0].route.join(" → ")}, first token ${(steps[0].ms / 1000).toFixed(1)} s, then ${perToken.toFixed(0)} ms per token`);
  check("the text matches", tok.decode(tokens) === index.greedy_text);
}

console.log("6. h on the wire vs step 2 in one process");
{
  const frames = sent.filter((s) => s.frame.session === mainSession);
  const hidden = [1, 2].map((hop) => frames.filter((s) => s.frame.kind === KIND.HIDDEN && s.frame.hop === hop));
  const steps = greedy.length;
  let identical = hidden[0].length === steps && hidden[1].length === steps;
  for (let i = 0; identical && i < steps; i++) {
    identical = sameBytes(hidden[0][i].frame.payload, reference.h1[i]) && sameBytes(hidden[1][i].frame.payload, reference.h2[i]);
  }
  const decodeBytes = hidden[0][1].frame.payload.byteLength + 16;
  check("every h sent between blocks is bit-identical", identical,
    `${steps * 2} frames, ${decodeBytes} bytes per hop per new token`);
  const fromPeers = [1, 2].map((hop) => new Set(hidden[hop - 1].map((s) => s.from)));
  check("each hop came from one phone, the one on the route", fromPeers.every((s) => s.size === 1));
}

console.log("7. Two askers at once");
{
  const other = otherPrompt;
  const solo = reference.otherTokens;
  const [a, b] = await Promise.all([
    collect(phones[0].ask(prompt, { maxNew: SHORT, stopIds: [EOS] })),
    collect(phones[1].ask(other, { maxNew: SHORT, stopIds: [EOS] })),
  ]);
  const routeA = a[0].route, routeB = b[0].route;
  check("the second asker gets a route on different phones", routeA.every((id) => !routeB.includes(id)),
    `${routeA.join(" → ")}  and  ${routeB.join(" → ")}`);
  check("both answers equal their solo answers", same(a.map((x) => x.token), greedy.slice(0, SHORT)) && same(b.map((x) => x.token), solo),
    JSON.stringify(tok.decode(b.map((x) => x.token))));
}

console.log("8. A phone leaves mid-answer");
{
  const LONG = 30;
  let leaver = null;
  const steps = await collect(asker.ask(prompt, { maxNew: LONG, stopIds: [EOS] }), (step, count) => {
    if (count === 2) {
      leaver = phones.find((p) => p.id === step.route[1]);
      leaver.close();
    }
  });
  phones.splice(phones.indexOf(leaver), 1);
  const last = steps.at(-1);
  check("the answer continues on another phone and is still exactly right",
    same(steps.map((x) => x.token), greedy.slice(0, LONG)) && last.reroutes === 1 && !last.route.includes(leaver.id),
    `${leaver.id} left after 2 tokens, rerouted to ${last.route.join(" → ")}, ${steps.length} of ${LONG} tokens match`);
  await until(() => !listed(leaver.id));
  check("the dashboard drops it", !listed(leaver.id));

  // Now the leaver's block has one holder. When that one leaves too, nobody can take over.
  const block = leaver.block.index;
  let error = null, lastHolder = null;
  try {
    await collect(asker.ask(prompt, { maxNew: LONG, stopIds: [EOS] }), (step, count) => {
      if (count === 2) {
        lastHolder = phones.find((p) => p.id === step.route[block]);
        lastHolder.close();
      }
    });
  } catch (err) {
    error = err.message;
  }
  phones.splice(phones.indexOf(lastHolder), 1);
  check("with no other holder of its block, the asker gets a clear error",
    new RegExp(`no other phone has block ${block + 1} ready`).test(error ?? ""), error ?? "no error");
}

console.log("9. Cleanup");
{
  const freed = await until(() => phones.every((p) => p.stage.sessions.length === 0));
  const left = phones.filter((p) => p.stage.sessions.length).map((p) => `${p.id}: ${p.stage.sessions}`);
  check("every phone has freed every session's KV cache", freed, left.join(" "));
  await until(() => watch.state.sessions.length === 0);
  check("the tracker has no sessions left", watch.state.sessions.length === 0);
}

console.log("10. Silent phones: busy versus frozen");
{
  // A phone that never answers pings, as a locked screen or a phone stuck in
  // a long prefill looks to the tracker. It takes the block left empty in
  // check 8 and serves it with this process's copy, but sits on the first
  // frame for longer than the heartbeat timeout before answering.
  const SILENT_MS = HEARTBEAT_MS + 4000;
  const frozen = new RawSocket(server.replace(/^http/, "ws") + "/ws", { autoPong: false });
  const welcome = await new Promise((resolve) => {
    frozen.on("open", () => frozen.send(JSON.stringify({ type: "hello" })));
    frozen.once("message", (data) => resolve(JSON.parse(data.toString())));
  });
  const stage = local[welcome.block.index];
  let first = true;
  frozen.on("message", async (data, isBinary) => {
    if (!isBinary) return;
    const f = decodeFrame(new Uint8Array(data).slice().buffer);
    if (first) {
      first = false;
      await wait(SILENT_MS);
    }
    const out = stage.forward(`frozen.${f.session}.${f.attempt}`, f.payload, f.pos, { lastOnly: true });
    const next = { hop: f.hop + 1, attempt: f.attempt, session: f.session };
    frozen.send(stage.hasOutput
      ? encodeFrame({ ...next, kind: KIND.NEXT, pos: f.pos + f.n, n: 1 }, Int32Array.of(argmax(out)))
      : encodeFrame({ ...next, kind: KIND.HIDDEN, pos: f.pos, n: f.n }, out));
  });
  frozen.send(JSON.stringify({ type: "ready" }));
  await until(() => watch.state.peers.find((p) => p.id === welcome.id)?.ready);
  const steps = await collect(asker.ask(prompt, { maxNew: 3, stopIds: [EOS] }));
  check("a phone silent for longer than the heartbeat timeout while it owes a reply is kept",
    steps[0].route.includes(welcome.id) && same(steps.map((x) => x.token), greedy.slice(0, 3)) && listed(welcome.id),
    `${welcome.id} on block ${welcome.block.index + 1}, silent ${(SILENT_MS / 1000).toFixed(0)} s, first token ${(steps[0].ms / 1000).toFixed(1)} s`);
  const t = performance.now();
  const dropped = await until(() => !listed(welcome.id), 15000);
  check("once idle and still silent, it is dropped", dropped,
    `${welcome.id} dropped after ${((performance.now() - t) / 1000).toFixed(1)} s`);
  frozen.terminate();
}

console.log("11. What phones and the dashboard get");
{
  await until(() => swarmState.get(asker.id)?.phones === watch.state.peers.length);
  const summary = swarmState.get(asker.id);
  const bytes = JSON.stringify(summary).length;
  check("phones get a small summary with holder counts, not the phone list",
    summary && !("peers" in summary) && summary.holders.length === 3 && summary.phones === watch.state.peers.length && bytes < 400,
    `${bytes} bytes for ${summary?.phones} phones`);
  const p = watch.state.peers.find((x) => x.id === asker.id);
  check("the dashboard gets each phone's ping and its measured time per token",
    watch.state.peers.every((x) => x.rtt != null) && watch.state.peers.some((x) => x.tokenMs != null) && p.served >= 0,
    watch.state.peers.map((x) => `${x.id} ping ${x.rtt?.toFixed(0)} ms token ${x.tokenMs?.toFixed(0) ?? "–"} ms`).join(", "));
  check("the tracker logs every finished question with its timing per hop",
    watch.state.events.some((e) => /session \d+ done: \d+ tokens, first token [\d.]+ s, then \d+ ms per token · per hop/.test(e)),
    watch.state.events.find((e) => /done:/.test(e))?.slice(9) ?? "");
  const t = watch.state.throughput;
  check("the dashboard gets swarm throughput: answer tokens, served tokens, speed per answer",
    t.generated > 0 && t.served > t.generated && t.perAnswer > 0 && t.answers > 0 && t.generatedPerSecWhileAnswering > 0,
    `${t.generated} answer tokens, ${t.served} served, ${t.perAnswer.toFixed(1)} tok/s per answer over ${t.answers} answers, ${t.generatedPerSecWhileAnswering.toFixed(1)} tok/s while answering`);
  const qr = await fetch(`${server}/qr.svg?text=${encodeURIComponent("https://example.trycloudflare.com")}`);
  const dash = await fetch(`${server}/dashboard`, { redirect: "manual" });
  check("/qr.svg draws a QR code and /dashboard leads to the dashboard",
    qr.ok && (await qr.text()).startsWith("<svg") && dash.headers.get("location") === "/swarm/web/dashboard.html");
}

for (const p of phones) p.close();
tracker.kill();
const passed = results.filter(Boolean).length;
console.log(`\n${passed}/${results.length} checks passed in ${((performance.now() - t0) / 1000).toFixed(0)} s`);
process.exit(passed === results.length ? 0 : 1);
