// Step 3 checks: does the swarm give the same answer as one model?
//
// Starts the real tracker, then runs six phones as Peer objects in this
// process. They fetch their weights over HTTP and talk only through the
// tracker's WebSocket, the same path a browser tab uses.
//
//  1. The tokenizer gives Hugging Face's ids, and decodes them back.
//  2. Frames survive encode/decode bit for bit.
//  3. Where phones go: a whole path first, then min_replica holders per
//     block, then the largest block splits; repairs when phones leave.
//  4. Asking before every block has a holder fails clearly.
//  5. Six phones end up two per block.
//  6. The greedy answer through the swarm equals the Python reference's
//     (Hugging Face's, for float32).
//  7. The h sent between phones is bit-identical to step 2's in-process run.
//  8. Two askers at once get different routes and their solo answers.
//  9. Routing is speed-aware: a slow phone is passed over, even for a fast
//     phone that is already answering.
// 10. A conversation keeps its KV caches between questions: a follow-up sends
//     only its new tokens, and survives a phone on its route leaving.
// 11. A phone leaving mid-answer: the answer is rerouted and is still exactly
//     right; when it was its block's last holder, another phone moves in.
// 12. When sessions end, every phone frees their KV caches.
// 13. A phone silent while it computes is kept; silent while idle, dropped.
// 14. Rebalancing live: a split in the middle of an answer, and a phone
//     moving to a block below min_replica; answers stay exactly right.
// 15. Phones get a small summary; the dashboard gets everything, and a QR code.
//
//   cd swarm && npm run check
//   node test/check.js WEIGHTS_DIR TESTVECTORS_DIR   # another export, e.g. a quantized one

