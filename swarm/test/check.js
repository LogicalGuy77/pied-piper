console.log("9. Speed-aware routing");
{
  // One block-2 phone gets 150 ms slower per frame. Two questions at once put
  // it on one of the routes, so the tracker measures it.
  const [slow, fast] = phones.filter((p) => p.block.index === 1);
  const original = slow.stage.forwardAsync;
  slow.stage.forwardAsync = async function (...args) {
    await wait(150);
    return original.apply(this, args);
  };
  const both = await Promise.all([
    collect(phones[0].ask(prompt, { maxNew: SHORT, stopIds: [EOS] })),
    collect(phones[3].ask(otherPrompt, { maxNew: SHORT, stopIds: [EOS] })),
  ]);
  const measured = both.some((steps) => steps[0].route[1] === slow.id);
  const token = (id) => watch.state.peers.find((p) => p.id === id)?.tokenMs;
  await until(() => token(slow.id) > 3 * token(fast.id));
  check("the slow phone's time per token is measured", measured && token(slow.id) > 3 * token(fast.id),
    `${slow.id} ${token(slow.id)?.toFixed(0)} ms, ${fast.id} ${token(fast.id)?.toFixed(0)} ms`);
  const alone = await collect(phones[0].ask(prompt, { maxNew: 3, stopIds: [EOS] }));
  const together = await Promise.all([
    collect(phones[0].ask(prompt, { maxNew: SHORT, stopIds: [EOS] })),
    collect(phones[3].ask(otherPrompt, { maxNew: SHORT, stopIds: [EOS] })),
  ]);
  const routes = [alone, ...together].map((steps) => steps[0].route);
  check("new questions go to the fast phone, even when it is already answering one",
    routes.every((r) => r[1] === fast.id) && same(together[1].map((x) => x.token), reference.otherTokens),
    routes.map((r) => r.join(" → ")).join(", "));
  slow.stage.forwardAsync = original;
}

console.log("10. A conversation keeps its KV cache between questions");
{
  const ask = (k) => collect(asker.ask(conversation.ids[k], { maxNew: TURN, stopIds: [EOS], keep: true }));
  const firstFrame = (session, from) => sent.slice(from).find((s) => s.from === asker.id && s.frame.session === session && s.frame.kind === KIND.TOKENS)?.frame;
  const t1 = await ask(0);
  const session = t1[0].session;
  await until(() => watch.state.sessions.some((s) => s.id === session && !s.active));
  const onRoute = t1[0].route.map((id) => phones.find((p) => p.id === id));
  check("after an answer, the conversation stays open and every phone on its route keeps the KV cache",
    same(t1.map((x) => x.token), conversation.answers[0]) &&
    onRoute.every((p) => p.stage.sessions.includes(`${session}.0`)) &&
    watch.state.sessions.some((s) => s.id === session && !s.active),
    `session ${session} idle, ${watch.state.sessions.find((s) => s.id === session)?.context} tokens cached on ${t1[0].route.join(" → ")}`);

  const mark = sent.length;
  const t2 = await ask(1);
  const frame = firstFrame(session, mark);
  const expectCached = conversation.ids[0].length + t1.length - 1;
  check("the follow-up reuses the session and sends only its new tokens",
    t2[0].session === session && t2[0].cached === expectCached && frame?.pos === expectCached && frame?.n === conversation.ids[1].length - expectCached,
    `${frame?.n} tokens sent instead of ${conversation.ids[1].length}`);
  check("its answer equals a fresh run on the whole conversation", same(t2.map((x) => x.token), conversation.answers[1]),
    JSON.stringify(tok.decode(t2.map((x) => x.token))));

  // A phone on the route leaves between questions; a new phone takes its place in the swarm.
  const leaver = phones.find((p) => p.id === t2[0].route[1]);
  leaver.close();
  phones.splice(phones.indexOf(leaver), 1);
  await until(() => !listed(leaver.id));
  phones.push(await startPeer());
  const mark3 = sent.length;
  const t3 = await ask(2);
  const replay = firstFrame(session, mark3);
  check("when a phone on the route left between questions, the next one replays the conversation and is still right",
    t3[0].session === session && !t3[0].route.includes(leaver.id) && replay?.pos === 0 &&
    replay?.n === conversation.ids[2].length && same(t3.map((x) => x.token), conversation.answers[2]),
    `${leaver.id} left, now ${t3[0].route.join(" → ")}, replayed ${replay?.n} tokens`);

  asker.endChat();
  const route = t3[0].route.map((id) => phones.find((p) => p.id === id));
  const freed = await until(() => route.every((p) => !p.stage.sessions.some((k) => k.startsWith(`${session}.`))) &&
    !watch.state.sessions.some((s) => s.id === session));
  check("a new chat ends the session and frees its KV caches", freed);
}

console.log("11. A phone leaves mid-answer");
{
  const LONG = 30;
  let leaver = null;
  const steps = await collect(asker.ask(prompt, { maxNew: LONG, stopIds: [EOS] }), (step, count) => {
    if (count === 2) {
      leaver = phones.find((p) => p.id === step.route[1]);
      leaver.close();
    }
  });
  phones.splice(phones.indexOf(leaver), 1);
  const last = steps.at(-1);
  check("the answer continues on another phone and is still exactly right",
    same(steps.map((x) => x.token), greedy.slice(0, LONG)) && last.reroutes === 1 && !last.route.includes(leaver.id),
    `${leaver.id} left after 2 tokens, rerouted to ${last.route.join(" → ")}, ${steps.length} of ${LONG} tokens match`);
  await until(() => !listed(leaver.id));
  check("the dashboard drops it", !listed(leaver.id));

  // Now the leaver's block has one holder. When that one leaves too, a phone
  // from a block with two moves in, loads the block, and the answer goes on.
  const block = leaver.block.index;
  let lastHolder = null, error = null, after = [];
  const mark = trackerLog.length;
  try {
    after = await collect(asker.ask(prompt, { maxNew: LONG, stopIds: [EOS] }), (step, count) => {
      if (count === 2) {
        lastHolder = phones.find((p) => p.id === step.route[block]);
        lastHolder.close();
      }
    });
  } catch (err) {
    error = err.message;
  }
  phones.splice(phones.indexOf(lastHolder), 1);
  const moved = phones.find((p) => p.id === after.at(-1)?.route[block]);
  check("when its block's last holder leaves, a phone from a block with two moves in and the answer is still right",
    !error && same(after.map((x) => x.token), greedy.slice(0, LONG)) && moved?.stage.describe() === BLOCK_NAMES[block],
    error ?? `${lastHolder.id} left; ${trackerLog.slice(mark).find((e) => /moves to block/.test(e))?.slice(9) ?? "nobody moved"}; now ${after.at(-1).route.join(" → ")}`);
}

console.log("12. Cleanup");
{
  const freed = await until(() => phones.every((p) => p.stage.sessions.length === 0));
  const left = phones.filter((p) => p.stage.sessions.length).map((p) => `${p.id}: ${p.stage.sessions}`);
  check("every phone has freed every session's KV cache", freed, left.join(" "));
  await until(() => watch.state.sessions.length === 0);
  check("the tracker has no sessions left", watch.state.sessions.length === 0);
}

console.log("13. Silent phones: busy versus frozen");
{
  // A phone that never answers pings, as a locked screen or a phone stuck in
  // a long prefill looks to the tracker. It joins a block that check 11 left
  // with one phone and serves it with this process's copy, but sits on the
  // first frame for longer than the heartbeat timeout before answering.
  const SILENT_MS = HEARTBEAT_MS + 4000;
  const frozen = new RawSocket(server.replace(/^http/, "ws") + "/ws", { autoPong: false });
  const welcome = await new Promise((resolve) => {
    frozen.on("open", () => frozen.send(JSON.stringify({ type: "hello" })));
    frozen.once("message", (data) => resolve(JSON.parse(data.toString())));
  });
  const stage = local[welcome.block.index];
  let first = true;
  frozen.on("message", async (data, isBinary) => {
    if (!isBinary) return;
    const f = decodeFrame(new Uint8Array(data).slice().buffer);
    if (first) {
      first = false;
      await wait(SILENT_MS);
    }
    const out = stage.forward(`frozen.${f.session}.${f.attempt}`, f.payload, f.pos, { lastOnly: true });
    const next = { hop: f.hop + 1, attempt: f.attempt, session: f.session };
    frozen.send(stage.hasOutput
      ? encodeFrame({ ...next, kind: KIND.NEXT, pos: f.pos + f.n, n: 1 }, Int32Array.of(argmax(out)))
      : encodeFrame({ ...next, kind: KIND.HIDDEN, pos: f.pos, n: f.n }, out));
  });
  frozen.send(JSON.stringify({ type: "ready", block: welcome.block.id }));
  await until(() => watch.state.peers.find((p) => p.id === welcome.id)?.ready);
  // Its block's other phone leaves, so the route has to go through it.
  const other = phones.find((p) => p.block.id === welcome.block.id);
  if (other === asker) asker = phones.find((p) => p !== other);
  other.close();
  phones.splice(phones.indexOf(other), 1);
  await until(() => !listed(other.id));
  const steps = await collect(asker.ask(prompt, { maxNew: 3, stopIds: [EOS] }));
  check("a phone silent for longer than the heartbeat timeout while it owes a reply is kept",
    steps[0].route.includes(welcome.id) && same(steps.map((x) => x.token), greedy.slice(0, 3)) && listed(welcome.id),
    `${welcome.id} on block ${welcome.block.index + 1}, silent ${(SILENT_MS / 1000).toFixed(0)} s, first token ${(steps[0].ms / 1000).toFixed(1)} s`);
  const t = performance.now();
  const dropped = await until(() => !listed(welcome.id), 15000);
  check("once idle and still silent, it is dropped", dropped,
    `${welcome.id} dropped after ${((performance.now() - t) / 1000).toFixed(1)} s`);
  frozen.terminate();
}

console.log("14. Rebalancing live");
{
  // The tracker's view: each block's range and how many phones hold it.
  const layout = () => watch.state.blocks.map((b) => `${b.start}-${b.end}×${watch.state.peers.filter((p) => p.block === b.index).length}`).join(" ");
  const settled = () => until(() => watch.state.peers.length === phones.length && watch.state.peers.every((p) => p.ready), 10000);
  const LONG = 30;
  await settled();
  const start = layout();
  for (let i = 0; i < 3; i++) phones.push(await startPeer());
  await settled();
  check("new phones fill every block up to min_replica first", layout() === "0-8×2 8-23×2 23-30×2", `${start} → ${layout()}`);

  phones.push(await startPeer());
  await settled();
  check("the next one joins the block with the most compute as an extra replica",
    layout() === "0-8×2 8-23×3 23-30×2", `${phones.at(-1).id} on block 2: ${layout()}`);

  // The phone after that splits block 2, while an answer is going through it.
  const old = watch.state.peers.filter((p) => p.block === 1).sort((a, b) => a.joinedAt - b.joinedAt).map((p) => phones.find((x) => x.id === p.id));
  let joining = null;
  const mark = trackerLog.length;
  const steps = await collect(asker.ask(prompt, { maxNew: LONG, stopIds: [EOS] }), (step, count) => {
    if (count === 2) joining = startPeer();
  });
  const splitter = await joining;
  phones.push(splitter);
  await settled();
  const last = steps.at(-1);
  check("the phone that brings it to 2 × min_replica splits it in the middle of an answer, and the answer is still exactly right",
    same(steps.map((x) => x.token), greedy.slice(0, LONG)) && last.route.length === 4 && last.reroutes === 0 && layout() === "0-8×2 8-15×2 15-23×2 23-30×2",
    `${steps[1].route.join(" → ")} became ${last.route.join(" → ")}; ${trackerLog.slice(mark).find((e) => /splits/.test(e))?.slice(9)}`);
  const halves = [old[0], old[1], old[2], splitter].map((p) => p.stage.describe());
  check("its two earliest phones take the first half; the third and the new phone the second; each holds only its half",
    same(halves, ["layers 8–14", "layers 8–14", "layers 15–22", "layers 15–22"]),
    [old[0], old[1], old[2], splitter].map((p, i) => `${p.id} ${halves[i]}`).join(", "));
  const after = await collect(asker.ask(otherPrompt, { maxNew: SHORT, stopIds: [EOS] }));
  check("a new question through the four blocks is right too", same(after.map((x) => x.token), reference.otherTokens), after[0].route.join(" → "));

  // One more phone makes block 4 the one with a spare. A phone of block 1
  // leaving leaves it below min_replica, so the spare moves there.
  phones.push(await startPeer());
  await settled();
  const spare = layout();
  const leaver = phones.find((p) => p.block.start === 0 && p !== asker);
  const mark2 = trackerLog.length;
  leaver.close();
  phones.splice(phones.indexOf(leaver), 1);
  await until(() => !listed(leaver.id));
  await settled();
  const moved = trackerLog.slice(mark2).find((e) => /moves to block 1/.test(e));
  const movedPhone = phones.find((p) => moved?.includes(` ${p.id} moves`));
  const answer = await collect(asker.ask(prompt, { maxNew: SHORT, stopIds: [EOS] }));
  check("when a block falls below min_replica, a phone moves to it from a block with more than min_replica",
    spare === "0-8×2 8-15×2 15-23×2 23-30×3" && layout() === "0-8×2 8-15×2 15-23×2 23-30×2" &&
    movedPhone?.stage.describe() === BLOCK_NAMES[0] && same(answer.map((x) => x.token), greedy.slice(0, SHORT)),
    `${spare}; ${leaver.id} left; ${moved?.slice(9) ?? "nobody moved"}`);
}

