console.log("3. Where phones go");
const manifest = JSON.parse(await readFile(join(WEIGHTS, "manifest.json"), "utf8"));
{
  const cost = costModel(manifest);
  const L = manifest.config.num_layers;
  // Phones join one at a time, as the tracker places them; a split gives the
  // first half minReplica of the old holders and the second half the rest
  // plus the joining phone. Returns the layout after each join.
  const join = (minBlocks, minReplica, n) => {
    const cut = initialCut(manifest, minBlocks);
    const blocks = cut.slice(0, -1).map((start, i) => ({ start, end: cut[i + 1] }));
    const holders = blocks.map(() => 0);
    const layouts = [];
    for (let k = 0; k < n; k++) {
      const place = placeJoin(blocks, holders, { minReplica, cost });
      if (place.split === undefined) holders[place.block]++;
      else {
        const b = blocks[place.split], m = splitPoint(b, cost);
        blocks.splice(place.split, 1, { start: b.start, end: m }, { start: m, end: b.end });
        holders.splice(place.split, 1, minReplica, holders[place.split] + 1 - minReplica);
      }
      layouts.push(blocks.map((b, i) => `${b.start}-${b.end}${b.end === L ? "+out" : ""}×${holders[i]}`).join(" "));
    }
    return layouts;
  };
  check("the first cut balances memory: 3 blocks are 0, 8, 23, 30", same(initialCut(manifest, 3), BOUNDARIES),
    `compute in layers: ${[0, 1, 2].map((i) => cost({ start: BOUNDARIES[i], end: BOUNDARIES[i + 1] }).toFixed(1)).join(", ")}; the output layer counts as ${(cost({ start: 29, end: 30 }) - 1).toFixed(1)}`);
  const seq = join(3, 2, 10);
  const expect = [
    "0-8×1 8-23×0 23-30+out×0", "0-8×1 8-23×1 23-30+out×0", "0-8×1 8-23×1 23-30+out×1",
    "0-8×2 8-23×1 23-30+out×1", "0-8×2 8-23×2 23-30+out×1", "0-8×2 8-23×2 23-30+out×2",
    "0-8×2 8-23×3 23-30+out×2", "0-8×2 8-15×2 15-23×2 23-30+out×2",
    "0-8×2 8-15×2 15-23×2 23-30+out×3", "0-8×2 8-15×2 15-23×2 23-29×2 29-30+out×2",
  ];
  check("min_blocks 3, min_replica 2: a path at 3 phones, 2 per block at 6, the 7th on the largest block, the 8th splits it",
    same(seq, expect), seq.findIndex((x, i) => x !== expect[i]) < 0 ? `10 phones: ${seq.at(-1)}` : `phone ${seq.findIndex((x, i) => x !== expect[i]) + 1}: ${seq.find((x, i) => x !== expect[i])}`);
  const one = join(3, 1, 4);
  check("min_replica 1: the 4th phone splits the largest block right away", one[3] === "0-8×1 8-15×1 15-23×1 23-30+out×1", one[3]);
  const cases = [[[0, 2, 2], { from: 1, to: 0 }], [[1, 0, 3], { from: 2, to: 1 }], [[1, 2, 3], { from: 2, to: 0 }],
    [[1, 2, 2], null], [[0, 1, 1], null], [[2, 2, 2], null]];
  const bad = cases.filter(([h, want]) => !same(repairMove(h, 2), want));
  check("repairs: an empty block takes a phone from the fullest block that can spare one; a block below min_replica only from one above it",
    bad.length === 0, bad.map(([h]) => JSON.stringify(h)).join(" ") || "6 cases");
}

// --- Local references, computed before any phone runs ---
// The test phones share this process, so a long computation here would stop
// them answering the tracker's heartbeat. Everything slow happens first.

const prompt = index.prompt_ids;
const greedy = index.greedy_tokens;
const otherPrompt = tok.chat([{ role: "user", content: "What is the capital of France?" }]);
const reference = { h1: [], h2: [], otherTokens: null };
const local = []; // the three blocks in this process; check 13's phone serves one of them
{
  const weights = await openWeights(WEIGHTS);
  for (let i = 0; i < 3; i++) local.push(await Stage.load({ ...weights, start: BOUNDARIES[i], end: BOUNDARIES[i + 1] }));
  let ids = Int32Array.from(prompt), pos = 0;
  for (let i = 0; i < greedy.length; i++) {
    reference.h1.push(local[0].forward("local", ids, pos));
    reference.h2.push(local[1].forward("local", reference.h1[i], pos));
    local[2].forward("local", reference.h2[i], pos, { lastOnly: true });
    pos += ids.length;
    ids = Int32Array.of(greedy[i]);
  }
  reference.otherTokens = generate(new Pipeline(local), "solo", otherPrompt, SHORT, new Set([EOS])).tokens;
}

// A three-question conversation, built the way the phone page builds it: each
// question extends the previous prompt and the answer exactly as generated.
// Each turn's reference answer is a fresh run on the whole conversation.
const TURN = 12;
const conversation = { ids: [], answers: [] };
{
  const pipe = new Pipeline(local);
  let ids = otherPrompt;
  for (const [k, question] of ["And of Germany?", "And of Italy?", null].entries()) {
    const answer = generate(pipe, `turn${k}`, ids, TURN, new Set([EOS])).tokens;
    pipe.drop(`turn${k}`);
    conversation.ids.push(ids);
    conversation.answers.push(answer);
    if (!question) break;
    ids = [...ids, ...answer, ...(answer.at(-1) === EOS ? [] : [EOS]),
      ...tok.encode(`\n<|im_start|>user\n${question}<|im_end|>\n<|im_start|>assistant\n`)];
  }
}

// --- Start the tracker and the phones ---

// The heartbeat timeout is longer than the 5 s default: these phones answer
// pings from JS, and the reference work in this process can hold it for a
// few seconds. (A browser answers pings outside the page's JS.)
const HEARTBEAT_MS = 8000;
const tracker = spawn(process.execPath, [join(ROOT, "swarm", "tracker.js"), "--port", "0", "--host", "127.0.0.1", "--weights", WEIGHTS,
  "--heartbeat-timeout", String(HEARTBEAT_MS)], { stdio: ["ignore", "pipe", "inherit"] });
const trackerLog = [];
const server = await new Promise((resolve, reject) => {
  tracker.on("exit", (code) => reject(new Error(`tracker exited with ${code}`)));
  tracker.stdout.on("data", (chunk) => {
    trackerLog.push(...chunk.toString().trim().split("\n"));
    const m = chunk.toString().match(/listening on (https?:\S+)/);
    if (m) resolve(m[1]);
  });
});

// Every phone fetches over HTTP; the first fetch of each file is shared, so
// six phones in one process don't hold six copies of the weights.
const fetched = new Map();
const sharedRead = (name) => {
  if (!fetched.has(name)) {
    fetched.set(name, fetch(`${server}/weights/${name}`).then((r) => {
      if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
      return r.arrayBuffer();
    }));
  }
  return fetched.get(name);
};

// The dashboard's view: the tracker's full state.
const watch = { state: null, messages: 0 };
{
  const ws = new RawSocket(server.replace(/^http/, "ws") + "/ws");
  ws.on("open", () => ws.send(JSON.stringify({ type: "watch" })));
  ws.on("message", (data) => {
    watch.state = JSON.parse(data.toString());
    watch.messages++;
  });
  await until(() => watch.state);
}
const listed = (id) => watch.state.peers.some((p) => p.id === id);

const sent = []; // every binary frame any phone sends: { from, frame }
const swarmState = new Map(); // phone id -> latest swarm summary it received
async function startPeer() {
  const peer = new Peer({ server, readFile: sharedRead });
  peer.tap = (buf) => sent.push({ from: peer.id, frame: decodeFrame(buf.slice(0)) });
  peer.onEvent = (e) => e.type === "swarm" && swarmState.set(peer.id, e);
  await peer.connect();
  await peer.load();
  return peer;
}
