// Step 2 checks: does the JS stage engine reproduce the Python reference?
//
// 1. Weight files are intact.
// 2. Prefill: h after the embedding and every layer, and logits, match testvectors/.
// 3. Decode steps through the KV cache match testvectors/.
// 4. Greedy generation through the 3-block split gives the reference tokens.
// 5. Other splits, and one-token-at-a-time prefill, are bit-identical to it.
// 6. Interleaved sessions on shared stages don't affect each other.
//
//   cd engine && npm run check        # WASM SIMD kernels
//   cd engine && npm run check:js     # the plain JS kernels
//   cd engine && npm run check:int8   # the int8 export against testvectors-int8/

import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { generate, generateStream, Pipeline } from "../src/pipeline.js";
import { openTestVectors, openWeights, sha256File } from "../src/node-files.js";
import { Stage } from "../src/stage.js";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const WEIGHTS = process.argv[2] ?? join(ROOT, "weights", "smollm2-135m-instruct");
const VECTORS = process.argv[3] ?? join(ROOT, "testvectors");
const SHORT = 4; // tokens generated by the extra runs in checks 5 and 6

const results = [];
function check(name, ok, detail = "") {
  results.push(ok);
  console.log(`  ${ok ? "PASS" : "FAIL"}  ${name}${detail ? `  (${detail})` : ""}`);
}

function maxAbsDiff(a, b) {
  let m = 0;
  for (let i = 0; i < a.length; i++) m = Math.max(m, Math.abs(a[i] - b[i]));
  return m;
}

function maxAbs(a) {
  let m = 0;
  for (let i = 0; i < a.length; i++) m = Math.max(m, Math.abs(a[i]));
  return m;
}

function bitEqual(a, b) {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (!Object.is(a[i], b[i])) return false;
  return true;
}

const sameLogits = (xs, ys) => xs.length === ys.length && xs.every((x, i) => bitEqual(x, ys[i]));
const sameTokens = (xs, ys) => xs.length === ys.length && xs.every((x, i) => x === ys[i]);
const fmt = (b) => (b.length <= 6 ? `[${b.join(",")}]` : `[0,1,...,${b.at(-1)}]`);

// Keeps the larger value, and NaN once seen, so a NaN can never pass a check.
const worse = (a, b) => (Number.isNaN(a) || a >= b ? a : b);

// Compare a trace (h at each boundary) against rows of a [boundaries, n * d] reference.
function compareTrace(trace, reference, rowLength) {
  let worst = 0, at = 0;
  trace.forEach((h, i) => {
    const ref = reference.subarray(i * rowLength, (i + 1) * rowLength);
    const rel = maxAbsDiff(h, ref) / maxAbs(ref);
    if (worse(worst, rel) !== worst) { worst = rel; at = i; }
  });
  return { worst, label: at === 0 ? "embedding" : `layer ${at - 1}` };
}

const t0 = performance.now();
const weights = { ...(await openWeights(WEIGHTS)), kernels: process.env.KERNELS ?? "wasm" };
const { manifest } = weights;
const { index, arrays } = await openTestVectors(VECTORS);
const L = manifest.config.num_layers;
const d = manifest.config.hidden_size;
const eos = manifest.config.eos_token_id;
const stopIds = new Set(Array.isArray(eos) ? eos : [eos]);
const tol = index.tolerance;
const prompt = index.prompt_ids;
const expected = index.greedy_tokens;

console.log("\n1. Weight files");
const entries = [manifest.embed, manifest.final_norm, ...manifest.layers, ...(manifest.lm_head ? [manifest.lm_head] : [])];
const hashes = await Promise.all(entries.map((e) => sha256File(join(WEIGHTS, e.file))));
check("files match the sha256 in manifest.json", hashes.every((h, i) => h === entries[i].sha256), `${entries.length} files`);

console.log(`\n2. Prefill vs Python reference  (prompt: ${prompt.length} tokens)`);
const full = await Stage.load({ ...weights, start: 0, end: L });
let trace = [];
const prefillLogits = full.forward("tv", prompt, 0, { trace, lastOnly: true });
const prefill = compareTrace(trace, arrays["prefill_hidden.bin"], prompt.length * d);
check(`hidden state after the embedding and all ${L} layers`, trace.length === L + 1 && prefill.worst < tol.hidden_rel,
  `worst relative error ${prefill.worst.toExponential(1)}, after ${prefill.label}`);
const prefillDiff = maxAbsDiff(prefillLogits, arrays["prefill_logits_last.bin"]);
check("logits at the last prompt position", prefillDiff < tol.logits_abs, `max abs diff ${prefillDiff.toExponential(1)}`);

console.log(`\n3. Decode steps through the KV cache  (${index.decode_steps.length} steps)`);
let decodeWorst = { worst: 0, label: "" }, decodeLogitsDiff = 0;
index.decode_steps.forEach(({ token, pos }, k) => {
  trace = [];
  const logits = full.forward("tv", [token], pos, { trace });
  const rowLength = (L + 1) * d;
  const r = compareTrace(trace, arrays["decode_hidden.bin"].subarray(k * rowLength, (k + 1) * rowLength), d);
  if (worse(decodeWorst.worst, r.worst) !== decodeWorst.worst) decodeWorst = { worst: r.worst, label: `step ${k + 1}, ${r.label}` };
  const vocab = manifest.config.vocab_size;
  decodeLogitsDiff = Math.max(decodeLogitsDiff, maxAbsDiff(logits, arrays["decode_logits.bin"].subarray(k * vocab, (k + 1) * vocab)));
});
check("hidden state at every boundary", decodeWorst.worst < tol.hidden_rel,
  `worst relative error ${decodeWorst.worst.toExponential(1)}, ${decodeWorst.label}`);
check("logits", decodeLogitsDiff < tol.logits_abs, `max abs diff ${decodeLogitsDiff.toExponential(1)}`);

const arch = [0, 8, L - 8, L];
console.log(`\n4. Greedy generation through the 3-block split ${fmt(arch)}`);
const archPipe = await Pipeline.load({ ...weights, boundaries: arch });
const tGen = performance.now();
let firstMs = 0;
const steps0 = [];
for (const step of generateStream(archPipe, "s", prompt, expected.length, stopIds)) {
  firstMs ||= performance.now() - tGen;
  steps0.push(step);
}
const genMs = performance.now() - tGen;
const base = { tokens: steps0.map((s) => s.token), logits: steps0.map((s) => s.logits) };
check(`tokens identical to the Python reference${manifest.dtype === "int8" ? " (int8)" : " (and Hugging Face)"}`,
  sameTokens(base.tokens, expected), `${expected.length} tokens`);
console.log(`        answer: ${JSON.stringify(index.greedy_text)}`);

console.log(`\n5. Other splits vs ${fmt(arch)}  (first ${SHORT} tokens, h crosses each boundary as raw bytes)`);
const prefix = { tokens: base.tokens.slice(0, SHORT), logits: base.logits.slice(0, SHORT) };
for (const b of [[0, L], [0, L / 2, L], [0, 1, L - 1, L], Array.from({ length: L + 1 }, (_, i) => i)]) {
  const run = generate(await Pipeline.load({ ...weights, boundaries: b }), "s", prompt, SHORT, stopIds);
  check(`split ${fmt(b)}: same tokens, bit-identical logits`, sameTokens(run.tokens, prefix.tokens) && sameLogits(run.logits, prefix.logits),
    `${b.length - 1} stage${b.length > 2 ? "s" : ""}`);
}
const oneByOne = generate(await Pipeline.load({ ...weights, boundaries: arch }), "s", prompt, SHORT, stopIds, "one_by_one");
check("prompt one token at a time: same tokens, bit-identical logits",
  sameTokens(oneByOne.tokens, prefix.tokens) && sameLogits(oneByOne.logits, prefix.logits));

console.log(`\n6. Sessions  (two questions on the same stages, split ${fmt(arch)})`);
const promptB = prompt.slice(0, 21).concat(prompt.slice(-3)); // the system prompt, then a bare assistant turn
const soloB = generate(await Pipeline.load({ ...weights, boundaries: arch }), "b", promptB, SHORT, stopIds);
const shared = await Pipeline.load({ ...weights, boundaries: arch });
const streams = new Map([
  ["a", generateStream(shared, "a", prompt, SHORT, stopIds)],
  ["b", generateStream(shared, "b", promptB, SHORT, stopIds)],
]);
const steps = { a: [], b: [] };
while (streams.size) {
  for (const [id, stream] of streams) {
    const next = stream.next();
    if (next.done) streams.delete(id);
    else steps[id].push(next.value);
  }
}
const asRun = (s) => ({ tokens: s.map((x) => x.token), logits: s.map((x) => x.logits) });
const a = asRun(steps.a), bRun = asRun(steps.b);
check("interleaved sessions match running each alone, bit for bit",
  sameTokens(a.tokens, prefix.tokens) && sameLogits(a.logits, prefix.logits) &&
  sameTokens(bRun.tokens, soloB.tokens) && sameLogits(bRun.logits, soloB.logits));
check("every stage holds one KV cache per session", shared.stages.every((s) => s.sessions.sort().join() === "a,b"));
shared.drop("a");
let restarted = false;
try { shared.forward("a", [prompt[0]], 0); restarted = true; } catch {}
check("drop() frees a session so it can start again at position 0",
  restarted && shared.stages.every((s) => s.sessions.includes("b")));
let rejected = false;
try { shared.forward("b", [1], 0); } catch { rejected = true; }
check("a token at the wrong position is rejected", rejected);

console.log(`\n7. Kernels`);
check(`every stage runs on the ${weights.kernels === "js" ? "plain JS" : "WASM SIMD"} kernels`,
  archPipe.stages.every((s) => s.kernels === (weights.kernels === "js" ? "js" : "wasm")));

console.log(`\nSpeed on this machine (${archPipe.stages[0].kernels === "wasm" ? "WASM SIMD" : "plain JS"}, one thread)`);
const decodeMs = archPipe.ms.map((ms) => ms);
const totalMs = decodeMs.reduce((x, y) => x + y, 0);
console.log(`  ${expected.length} tokens in ${(genMs / 1000).toFixed(1)} s: first token ${(firstMs / 1000).toFixed(2)} s ` +
  `(the ${prompt.length}-token prompt), then ${((genMs - firstMs) / (expected.length - 1)).toFixed(0)} ms per token`);
archPipe.stages.forEach((s, i) => {
  console.log(`  stage ${i + 1}  ${s.describe().padEnd(26)} ${(s.weightBytes / 1e6).toFixed(1).padStart(6)} MB  ` +
    `${((decodeMs[i] / totalMs) * 100).toFixed(0).padStart(3)}% of compute`);
});

const passed = results.filter(Boolean).length;
console.log(`\n${passed}/${results.length} checks passed in ${((performance.now() - t0) / 1000).toFixed(0)} s`);
process.exit(passed === results.length ? 0 : 1);
